#!/bin/sh
# Generate an owner-only .env with fresh high-entropy, URL-safe secrets.
#
# Hex output is used deliberately: it contains no URI-reserved characters, so the
# values are safe inside the DATABASE_URL and VALKEY_URL connection strings.
# Refuses to overwrite an existing .env. Requires openssl.
set -eu
cd "$(dirname "$0")/.."

if [ -e .env ]; then
  echo ".env already exists; refusing to overwrite. Move it aside first." >&2
  exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl is required to generate secrets." >&2
  exit 1
fi

gen() { openssl rand -hex 32; }

umask 077
{
  echo "# Generated by scripts/generate-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
  echo "# Set PUBLIC_SITE_HOST to your bare DNS name before a production deploy."
  echo "# Keep PUBLIC_SITE_INDEXABLE and PUBLIC_COMMERCE_INQUIRIES_ENABLED false until content and policy are approved."
  echo "POSTGRES_PASSWORD=$(gen)"
  echo "APP_DB_PASSWORD=$(gen)"
  echo "VALKEY_PASSWORD=$(gen)"
  echo "INTERNAL_SERVICE_TOKEN=$(gen)"
  echo "PUBLIC_SITE_HOST="
  echo "PUBLIC_SITE_INDEXABLE=false"
  echo "PUBLIC_REQUIRED_LOCALES=gu,hi,en"
  echo "PUBLIC_COMMERCE_INQUIRIES_ENABLED=false"
  echo "COMMERCE_POLICY_VERSION="
  echo "PUBLIC_PRIVACY_POLICY_URL="
  echo "PUBLIC_APP_ORIGIN=http://localhost:3000"
  echo "WEB_PORT=3000"
  echo "OPENAI_API_KEY="
  echo "OPENAI_API_BASE=https://api.openai.com/v1"
  echo "AI_MODEL=gpt-4o-mini"
} > .env

chmod 600 .env
echo "Wrote .env (mode 600) with four fresh secrets."
echo "Next: set PUBLIC_SITE_HOST, then run 'docker compose -f compose.yaml -f compose.production.yaml config --quiet'."
